-- Initial schema: users and their model-scored loan applications.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255)                NOT NULL,
    email         VARCHAR(255)                NOT NULL,
    password_hash VARCHAR(255)                NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE loan_applications (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT                      NOT NULL REFERENCES users (id) ON DELETE CASCADE,

    -- Applicant inputs
    applicant_name       VARCHAR(255)                NOT NULL,
    age                  INTEGER                     NOT NULL,
    income               NUMERIC(15, 2)              NOT NULL,
    loan_amount          NUMERIC(15, 2)              NOT NULL,
    employment_years     INTEGER                     NOT NULL,
    credit_history_years INTEGER                     NOT NULL,
    previous_default     BOOLEAN                     NOT NULL,
    home_ownership       VARCHAR(20)                 NOT NULL,
    loan_intent          VARCHAR(30)                 NOT NULL,

    -- Model output (stored so past results stay stable when the model is retrained)
    default_probability  NUMERIC(6, 5)               NOT NULL CHECK (default_probability BETWEEN 0 AND 1),
    risk_score           INTEGER                     NOT NULL CHECK (risk_score BETWEEN 0 AND 100),
    risk_label           VARCHAR(10)                 NOT NULL CHECK (risk_label IN ('LOW', 'MEDIUM', 'HIGH')),
    breakdown            TEXT                        NOT NULL,
    model_version        VARCHAR(50)                 NOT NULL,

    created_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_loan_app_user ON loan_applications (user_id);
